  school_id,student_id,guardian_id,relation,is_primary_contact,authorized_pickup,custody_notes
)
select p.school_id,s.id,g.id,src.relation,src.is_primary_contact,src.authorized_pickup,src.custody_notes
from src
cross join p
join public.students s on s.school_id=p.school_id and s.legacy_id=src.student_legacy_id
join public.guardians g on g.school_id=p.school_id and g.migration_key=src.guardian_key
on conflict (student_id,guardian_id) do update set
  relation=excluded.relation,
  is_primary_contact=excluded.is_primary_contact,
  authorized_pickup=excluded.authorized_pickup,
  custody_notes=excluded.custody_notes;

